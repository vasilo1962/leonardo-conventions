 md+='\n\n## '+t.h[3]+'\n\n| Stayman | '+t.h[3]+' |\n| --- | --- |\n';
 for(let i=0;i<3;i++)md+=`| **${['2♦','2♥','2♠'][i]}** | ${t.answers[i]} |\n`;
